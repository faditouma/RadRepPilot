function preserveInitialCapital(source: string, translated: string) {
  if (!source || source[0] !== source[0].toUpperCase()) return translated;
  return translated.charAt(0).toUpperCase() + translated.slice(1);
}

export function translateClinicalExactText(value: string, language: InterfaceLanguage): string {
  return language === 'fr' ? exactClinicalFrench[value] ?? value : value;
}

export function translateClinicalDisplayText(value: string, language: InterfaceLanguage): string {
  if (language !== 'fr' || !value.trim()) return value;

  const exact = translateClinicalExactText(value, language);
  if (exact !== value) return exact;

  let translated = value;
  for (const [pattern, replacement] of phraseRules) translated = translated.replace(pattern, replacement);

  translated = translated
    .replace(/\s+([,.;:])/g, '$1')
    .replace(/\s{2,}/g, ' ')
    .trim();

  return preserveInitialCapital(value, translated);
}

